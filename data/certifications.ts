/** Number of certificates per domain (secondary domains included). */
export function countByDomain(): Record<CertDomain, number> {
  const counts = Object.fromEntries(certDomains.map((d) => [d, 0])) as Record<CertDomain, number>;
  for (const cert of certifications) {
    for (const d of cert.domains) counts[d] += 1;
  }
  return counts;
}
